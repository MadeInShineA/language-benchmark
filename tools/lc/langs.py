"""Per-language knowledge: where solutions live, how stubs and glue code are generated,
how to build and how to invoke the runner.

Runner contract (every language implements it in its own runner):

    runner <problem_dir> <cases.json> <iters> <warmup>

It calls the solution warmup+iters times per case (fresh copy of the input each time,
copying is not timed) and prints one JSON line on stdout:

    {"cases": [{"ns": <median ns of the timed calls>, "result": <last return value>}, ...]}

If the function returns void (in-place problems), the result is the mutated parameter
given by meta["output"]["paramindex"].
"""

from __future__ import annotations

import re
from pathlib import Path

from .core import ROOT, Problem

GENERATED = "Code generated by tools/lc. DO NOT EDIT."


def fill_todo(snippet: str, stmt: str) -> str:
    """Put a placeholder statement in the empty function body of a LeetCode snippet."""
    lines = snippet.rstrip("\n").split("\n")
    for i in range(1, len(lines)):
        prev = lines[i - 1].rstrip()
        if lines[i].strip() == "" and prev.endswith(("{", ":")):
            indent = len(prev) - len(prev.lstrip()) + 4
            lines[i] = " " * indent + stmt
            return "\n".join(lines)
    # Python snippets end right after the signature
    if lines[-1].rstrip().endswith(":"):
        prev = lines[-1]
        lines.append(" " * (len(prev) - len(prev.lstrip()) + 4) + stmt)
    return "\n".join(lines)


def split_params(sig: str) -> list[str]:
    """Split 'a: Vec<i32>, b: HashMap<i32, i32>' on top-level commas."""
    out, depth, cur = [], 0, ""
    for ch in sig:
        depth += ch in "<(["
        depth -= ch in ">)]"
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def void_index(p: Problem) -> int | None:
    if p.meta["return"]["type"] == "void":
        return p.meta.get("output", {}).get("paramindex", 0)
    return None


class Lang:
    name: str
    leetcode_slug: str
    dir: Path

    def solution_path(self, p: Problem) -> Path:
        raise NotImplementedError

    def stub(self, p: Problem) -> str:
        raise NotImplementedError

    def sync(self, problems: list[Problem]) -> None:
        """(Re)generate glue code for every problem that has a solution file."""

    def build_cmd(self) -> list[str] | None:
        return None

    def run_cmd(self, p: Problem, cases: Path, iters: int, warmup: int) -> list[str]:
        raise NotImplementedError

    # helpers
    def has_solution(self, p: Problem) -> bool:
        return self.solution_path(p).exists()

    def scaffold(self, p: Problem) -> Path | None:
        """Write the solution stub if it doesn't exist yet. Never overwrites."""
        path = self.solution_path(p)
        if path.exists() or p.snippet(self.leetcode_slug) is None:
            return None
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(self.stub(p))
        return path


# ------------------------------------------------------------------ python

class Python(Lang):
    name = "python"
    leetcode_slug = "python3"
    dir = ROOT / "python"

    def solution_path(self, p):
        return self.dir / "problems" / f"{p.id}.py"

    def stub(self, p):
        code = fill_todo(p.snippet("python3"), "raise NotImplementedError")
        return f"from typing import List, Optional\n\n\n{code}\n"

    def build_cmd(self):
        return ["uv", "sync", "--quiet", "--project", str(self.dir)]

    def run_cmd(self, p, cases, iters, warmup):
        return ["uv", "run", "--quiet", "--project", str(self.dir), "python",
                str(self.dir / "runner.py"), str(p.dir), str(cases), str(iters), str(warmup)]


# ------------------------------------------------------------------ rust

class Rust(Lang):
    name = "rust"
    leetcode_slug = "rust"
    dir = ROOT / "rust"

    def solution_path(self, p):
        return self.dir / "src" / "problems" / f"{p.id}.rs"

    def stub(self, p):
        return "pub struct Solution;\n\n" + fill_todo(p.snippet("rust"), "todo!()") + "\n"

    def sync(self, problems):
        problems = [p for p in problems if self.has_solution(p)]
        mods = "".join(f"pub mod {p.id};\n" for p in problems)
        (self.dir / "src" / "problems" / "mod.rs").write_text(f"// {GENERATED}\n{mods}")
        arms = "".join(self._arm(p) for p in problems)
        (self.dir / "src" / "registry.rs").write_text(f"""\
// {GENERATED}
#![allow(unused_imports)]
use crate::{{arg, Out, Thunk}};
use serde_json::Value;

pub fn prepare(id: &str, input: &Value) -> Result<Thunk, String> {{
    match id {{
{arms}        _ => Err(format!("no Rust registry entry for {{id}}")),
    }}
}}
""")

    def _arm(self, p: Problem) -> str:
        sig = re.search(r"pub fn (\w+)\s*\((.*?)\)", p.snippet("rust"), re.S)
        fn, params = sig.group(1), split_params(sig.group(2))
        lets, call_args = [], []
        for i, (name, decl) in enumerate(zip(p.param_names, params)):
            ty = decl.split(":", 1)[1].strip()
            lets.append(f'            let {"mut " if ty.startswith("&mut") else ""}a{i} = arg(input, "{name}")?;\n')
            call_args.append(("&mut " if ty.startswith("&mut") else "&" if ty.startswith("&") else "") + f"a{i}")
        call = f"Solution::{fn}({', '.join(call_args)})"
        vi = void_index(p)
        body = (f"{{ {call}; Box::new(a{vi}) as Box<dyn Out> }}" if vi is not None
                else f"Box::new({call}) as Box<dyn Out>")
        return (f'        "{p.id}" => {{\n'
                f"            use crate::problems::{p.id}::Solution;\n"
                + "".join(lets)
                + f"            Ok(Box::new(move || {body}))\n"
                f"        }}\n")

    def build_cmd(self):
        return ["cargo", "build", "--release", "--quiet", "--manifest-path", str(self.dir / "Cargo.toml")]

    def run_cmd(self, p, cases, iters, warmup):
        return [str(self.dir / "target" / "release" / "runner"), str(p.dir), str(cases), str(iters), str(warmup)]


# ------------------------------------------------------------------ go

class Go(Lang):
    name = "go"
    leetcode_slug = "golang"
    dir = ROOT / "go"

    def solution_path(self, p):
        return self.dir / "problems" / p.id / "solution.go"

    def stub(self, p):
        return f"package {p.id}\n\n" + fill_todo(p.snippet("golang"), 'panic("TODO")') + "\n"

    def sync(self, problems):
        problems = [p for p in problems if self.has_solution(p)]
        for p in problems:
            (self.solution_path(p).parent / "adapter_gen.go").write_text(self._adapter(p))
        imports = "".join(f'\t"lcbench/problems/{p.id}"\n' for p in problems)
        entries = "".join(f'\t"{p.id}": {p.id}.Prepare,\n' for p in problems)
        reg = self.dir / "registry" / "registry_gen.go"
        reg.parent.mkdir(parents=True, exist_ok=True)
        reg.write_text(f"""\
// {GENERATED}

package registry

import (
\t"encoding/json"
{imports})

var Problems = map[string]func(map[string]json.RawMessage) (func() any, error){{
{entries}}}
""")

    def _adapter(self, p: Problem) -> str:
        fn = p.meta["name"]
        sig = re.search(rf"func {fn}\s*\((.*?)\)", p.snippet("golang"), re.S)
        decls = split_params(sig.group(1))
        # 'a, b int' style: a param without a type takes the next one's
        types: list[str] = []
        for d in reversed(decls):
            parts = d.split(None, 1)
            types.insert(0, parts[1] if len(parts) == 2 else types[0])
        decode = "".join(
            f"\tvar a{i} {t}\n"
            f'\tif err := json.Unmarshal(in["{name}"], &a{i}); err != nil {{\n'
            f'\t\treturn nil, fmt.Errorf("{name}: %w", err)\n\t}}\n'
            for i, (name, t) in enumerate(zip(p.param_names, types))
        )
        call = f"{fn}({', '.join(f'a{i}' for i in range(len(types)))})"
        vi = void_index(p)
        ret = f"{call}; return a{vi}" if vi is not None else f"return {call}"
        return f"""\
// {GENERATED}

package {p.id}

import (
\t"encoding/json"
\t"fmt"
)

func Prepare(in map[string]json.RawMessage) (func() any, error) {{
{decode}\treturn func() any {{ {ret} }}, nil
}}
"""

    def build_cmd(self):
        return ["go", "-C", str(self.dir), "build", "-o", "bin/runner", "./cmd/runner"]

    def run_cmd(self, p, cases, iters, warmup):
        return [str(self.dir / "bin" / "runner"), str(p.dir), str(cases), str(iters), str(warmup)]


