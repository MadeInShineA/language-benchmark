class JS(Lang):
    name = "js"
    leetcode_slug = "typescript"
    dir = ROOT / "js"

    def solution_path(self, p):
        return self.dir / "problems" / f"{p.id}.ts"

    def stub(self, p):
        code = fill_todo(p.snippet("typescript"), 'throw new Error("TODO");')
        return f"{code}\n\nexport {{ {p.meta['name']} }};\n"

